#!/usr/bin/env node
// Writes assembly/generated/*.ts from the Rust SDK's tables, so both SDKs
// number every property, event kind and action kind alike (RFC 0001
// section 12). Run `npm run tables` after the Rust SDK's tables change; the
// engine test `sdk_props_tests` checks the property file against the
// engine's own table.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const rust = join(here, "../../rust/vera20k-sdk/src");
const out = join(here, "../assembly/generated");
mkdirSync(out, { recursive: true });

const header = (what) =>
  `// Generated by scripts/tables.js from the Rust SDK (${what}); do not edit.\n\n`;

/** `SCREAMING_SNAKE` → `PascalCase`. */
const pascal = (name) =>
  name.toLowerCase().split("_").map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join("");

/** The `pub const NAME: i32 = N;` lines inside `impl <type> {`. */
function implConsts(file, type) {
  const source = readFileSync(join(rust, file), "utf8");
  const start = source.indexOf(`impl ${type} {`);
  if (start < 0) throw new Error(`no impl ${type} in ${file}`);
  const body = source.slice(start, source.indexOf("\n}\n", start));
  const entries = [];
  for (const m of body.matchAll(/^\s*((?:\/\/\/.*\n\s*)*)pub const ([A-Z0-9_]+): i32 = (-?\d+);/gm)) {
    const doc = m[1].trim().split("\n").map((l) => l.trim().replace(/^\/\/\/ ?/, "")).filter(Boolean);
    entries.push({ name: pascal(m[2]), value: Number(m[3]), doc });
  }
  return entries;
}

function writeEnum(file, name, entries, what, comment) {
  let text = header(what) + `/** ${comment} */\nexport enum ${name} {\n`;
  for (const e of entries) {
    if (e.doc.length) text += `  /** ${e.doc.join(" ")} */\n`;
    text += `  ${e.name} = ${e.value},\n`;
  }
  writeFileSync(join(out, file), text + "}\n");
}

// Properties: one constant per property in ID order.
{
  const source = readFileSync(join(rust, "props.rs"), "utf8");
  const props = [...source.matchAll(/^\s*pub const (\w+): Prop = Prop\((\d+)\);/gm)].map((m) => [m[1], Number(m[2])]);
  let text = header("props.rs") +
    "/** A property ID (appendix section 7). A `.` in an engine name is written `_`. */\n" +
    "export type Prop = i32;\n\nexport namespace Prop {\n";
  for (const [name, id] of props) text += `  export const ${name}: Prop = ${id};\n`;
  writeFileSync(join(out, "props.ts"), text + "}\n");
}

writeEnum("events.ts", "Event", implConsts("triggers.rs", "Event"), "triggers.rs `Event`",
  "Event kinds (appendix 4), numbered as the engine raises them.");
writeEnum("actions.ts", "ActionKind", implConsts("lib.rs", "Action"), "lib.rs `Action`",
  "Atomic action kinds (appendix 5.3); stock actions keep their numbers 0..145.");
console.log("wrote", out);

// Event and decision views: the Rust SDK's `view!` and `decision!` blocks,
// as zero-allocation `@unmanaged` classes read in place.
const FIELDS = {
  key: [0, "i32"], kind: [4, "i32"], trigger: [8, "i64"], holder: [16, "i64"],
  subject: [24, "i64"], other: [32, "i64"], house: [40, "i64"], projectile: [48, "i64"],
  modifier: [56, "i64"], cell: [64, "i64"], value: [72, "i64"], value2: [80, "i64"],
  id: [88, "i32"], frame: [92, "i32"], x: [96, "i32"], y: [100, "i32"], z: [104, "i32"],
  args: [108, "i32"], target: [112, "i32"],
};
const camel = (snake) => snake.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const TS_TYPE = { Techno: "Techno", House: "House", Cell: "Cell", Modifier: "Modifier",
  TypeRef: "TypeRef", Prop: "Prop", Projectile: "Projectile", i64: "i64", i32: "i32", bool: "bool" };

function readExpr(expr, ty) {
  let m;
  const load = (field) => {
    const [at, t] = FIELDS[field] ?? (() => { throw new Error(`no record field ${field}`); })();
    return `load<${t}>(changetype<usize>(this), ${at})`;
  };
  if ((m = expr.match(/^(?:Techno|House|Cell|Modifier|TypeRef|Projectile)\(r\.(\w+)\)$/))) return load(m[1]);
  if ((m = expr.match(/^Prop\(r\.(\w+) as i32\)$/))) return `<i32>${load(m[1])}`;
  if ((m = expr.match(/^r\.(\w+) as i32$/))) return `<i32>${load(m[1])}`;
  if ((m = expr.match(/^r\.(\w+) (!=|==) (-?\d+)$/))) return `${load(m[1])} ${m[2]} ${m[3]}`;
  if ((m = expr.match(/^TypeRef::new\(NameKind::(\w+), r\.(\w+)\)$/))) return `TypeRef.make(NameKind.${m[1]}, ${load(m[2])})`;
  if ((m = expr.match(/^r\.(\w+)$/))) {
    const raw = load(m[1]);
    return FIELDS[m[1]][1] === ty || ty === "i64" && FIELDS[m[1]][1] === "i32" ? raw : `<${ty}>${raw}`;
  }
  return null;
}

function views(file, macro) {
  const source = readFileSync(join(rust, file), "utf8");
  const out = [];
  for (const block of source.matchAll(new RegExp(`${macro}!\\(\\n((?:.|\\n)*?)\\n\\);`, "g"))) {
    const body = block[1];
    const docLines = [];
    const lines = body.split("\n");
    let i = 0;
    for (; i < lines.length && lines[i].trim().startsWith("///"); i++) docLines.push(lines[i].trim().slice(3).trim());
    const name = lines[i].trim().replace(/ \{$/, "");
    const fields = [];
    let fieldDoc = [];
    for (i++; i < lines.length; i++) {
      const line = lines[i].trim();
      if (line.startsWith("///")) { fieldDoc.push(line.slice(3).trim()); continue; }
      const m = line.match(/^(\w+): ([^=]+?) = \|r\| (.+?),?$/);
      if (m) {
        fields.push({ name: camel(m[1]), ty: m[2].trim(), expr: m[3], doc: fieldDoc });
        fieldDoc = [];
      }
    }
    out.push({ name, doc: docLines, fields });
  }
  return out;
}

function viewClass(v, decision) {
  let text = v.doc.length ? `/** ${v.doc.join(" ")} */\n` : "";
  text += `@unmanaged\nexport class ${v.name} {\n`;
  for (const f of v.fields) {
    if (f.ty === "[i32; 3]") {
      text += "  /** Position in leptons. */\n";
      for (const [axis, at] of [["x", 96], ["y", 100], ["z", 104]])
        text += `  get ${axis}(): i32 {\n    return load<i32>(changetype<usize>(this), ${at});\n  }\n`;
      continue;
    }
    const ty = TS_TYPE[f.ty];
    const read = ty && readExpr(f.expr, ty);
    if (!read) throw new Error(`${v.name}.${f.name}: cannot translate ${f.ty} = ${f.expr}`);
    if (f.doc.length) text += `  /** ${f.doc.join(" ")} */\n`;
    text += `  get ${f.name}(): ${ty} {\n    return ${read};\n  }\n`;
  }
  text += `  /** The whole record. */\n  get record(): EventRecord {\n    return changetype<EventRecord>(this);\n  }\n`;
  if (decision) {
    text += "  /** The native result, before any module. */\n  get native(): i64 {\n    return this.request.native;\n  }\n";
    text += "  /** The result so far: the previous link's, or the native one. */\n  get previous(): i64 {\n    return this.request.previous;\n  }\n";
    text += "  /** Answers `value` (and marks the request handled). */\n  setResult(value: i64): void {\n    this.request.setResult(value);\n  }\n";
    text += "  /** The whole request. */\n  get request(): DecideRecord {\n    return changetype<DecideRecord>(this);\n  }\n";
  }
  return text + "}\n\n";
}

{
  let text = header("triggers.rs `view!`") +
    'import { Techno, House, Cell, Modifier, TypeRef, Projectile, NameKind } from "../core";\n' +
    'import { Prop } from "./props";\nimport { EventRecord } from "../records";\n\n';
  for (const v of views("triggers.rs", "view")) text += viewClass(v, false);
  writeFileSync(join(out, "views.ts"), text.trimEnd() + "\n");
}
// Decision views with a result area or helpers of their own: written by
// hand in assembly/decide.ts, so they are skipped here.
const HAND_WRITTEN_DECISIONS = new Set([
  "FireDecision", "FatalDamageDecision", "MissionStepDecision", "LaunchDecision",
  "ProjectileFrameDecision", "MoveFrameDecision", "PathFoundDecision", "ApproachPointDecision",
]);
{
  let text = header("decide.rs `decision!`") +
    'import { Techno, House, Cell, Modifier, TypeRef, Projectile, NameKind } from "../core";\n' +
    'import { Prop } from "./props";\nimport { EventRecord, DecideRecord } from "../records";\n\n';
  for (const v of views("decide.rs", "decision")) {
    if (!HAND_WRITTEN_DECISIONS.has(v.name)) text += viewClass(v, true);
  }
  writeFileSync(join(out, "decisions.ts"), text.trimEnd() + "\n");
}

// Client tables (appendix 7.10, 4.6, 5.4): the Rust SDK's `client.rs`
// `NodeKind` and `ClientEvent` enums and `Local` action constants.
{
  const source = readFileSync(join(rust, "client.rs"), "utf8");
  /** The `Name = N,` variants of `pub enum <type> {`, with their `///` docs. */
  const enumVariants = (type) => {
    const start = source.indexOf(`pub enum ${type} {`);
    if (start < 0) throw new Error(`no enum ${type} in client.rs`);
    const body = source.slice(start, source.indexOf("\n}\n", start));
    const entries = [];
    for (const m of body.matchAll(/^\s*((?:\/\/\/.*\n\s*)*)([A-Z]\w*) = (-?\d+),/gm)) {
      const doc = m[1].trim().split("\n").map((l) => l.trim().replace(/^\/\/\/ ?/, "")).filter(Boolean);
      entries.push({ name: m[2], value: Number(m[3]), doc });
    }
    return entries;
  };
  const enumText = (name, entries, comment) => {
    let text = `/** ${comment} */\nexport enum ${name} {\n`;
    for (const e of entries) {
      // Rust intra-doc links read as plain code here.
      const doc = e.doc.join(" ").replace(/\[`([^`]+)`\](\([^)]*\))?/g, "`$1`")
        .replace(/(?:sys::)?(\w+)::(\w+)/g, (_, type, member) => `${type}.${camel(member)}`);
      if (doc) text += `  /** ${doc} */\n`;
      text += `  ${e.name} = ${e.value},\n`;
    }
    return text + "}\n";
  };
  const text = header("client.rs `NodeKind`, `ClientEvent`, `Local`") +
    enumText("NodeKind", enumVariants("NodeKind"),
      "Node kinds (appendix 7.10). Modules create all but `CameoGrid`, which only layouts make.") + "\n" +
    enumText("ClientEvent", enumVariants("ClientEvent"),
      "Client event kinds (appendix 4.6), delivered to `client_on_events`.") + "\n" +
    enumText("ClientActionKind", implConsts("client.rs", "Local"),
      "Local action kinds (appendix 5.4) for `client_action`.");
  writeFileSync(join(out, "client_tables.ts"), text);
}
