#!/usr/bin/env node
// `vera20k build` and `vera20k watch`: compile a TypeScript module to
// `rules.wasm` or `ui.wasm` with the pinned AssemblyScript, as RFC 0001
// section 5a asks of the SDK's build command:
//
// - top-level code becomes the `vera_init` / `client_init` export, never a
//   `start` section (`--exportStart`);
// - no `env.abort`, `env.trace` or `env.seed` import: `abort` logs the
//   runtime error through the world's own `log` and traps
//   (assembly/abort.ts), and the SDK calls neither `trace` nor `Math.random`;
// - only the Wasm features the engine accepts (AssemblyScript's defaults:
//   mutable globals, sign extension, non-trapping conversions, bulk memory);
// - the `vera.*` custom sections written after compiling: `vera.actions`
//   from the `namedAction("Name", fn)` literals, `vera.vars` and
//   `vera.notify` from `vera.json`, and `vera.delivery`.
//
// Usage: vera20k init <dir> [--ui]
//        vera20k build [project dir] [--out file] [--debug]
//        vera20k watch [project dir] [--out file] [--debug]
//        vera20k generate [project dir]   (src/generated/ only, for tsc)

import { readFileSync, writeFileSync, mkdirSync, mkdtempSync, existsSync, watch, symlinkSync, rmSync, cpSync, readdirSync, renameSync, realpathSync } from "node:fs";
import { dirname, join, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { tmpdir } from "node:os";
import asc from "assemblyscript/asc";
import { actionKey } from "./keys.js";

const SDK = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** The SDK's delivery area: from address 8 below the 1 KiB the compiler leaves free (`--memoryBase 1024`). */
const DELIVERY_OFFSET = 8;
const DELIVERY_BYTES = 1016;
const MEMORY_BASE = 1024;

const WORLDS = {
  rules: { exports: "assembly/exports.ts", start: "vera_init", out: "build/rules.wasm", abort: "simAbort" },
  ui: { exports: "assembly/client/exports.ts", start: "client_init", out: "build/ui.wasm", abort: "clientAbort" },
};

const SCOPES = { global: 0, house: 1, object: 2 };
const VISIBILITY = { private: 0, allies: 1, insight: 2, "in-sight": 2, public: 3 };

function fail(message) {
  const error = new Error(message);
  error.vera = true;
  throw error;
}

function readConfig(dir) {
  const path = join(dir, "vera.json");
  const config = existsSync(path) ? JSON.parse(readFileSync(path, "utf8")) : {};
  const kind = config.kind ?? "rules";
  if (!WORLDS[kind]) fail(`vera.json: kind must be "rules" or "ui", not ${JSON.stringify(kind)}`);
  return {
    kind,
    entry: config.entry ?? "src/index.ts",
    out: config.out ?? WORLDS[kind].out,
    vars: config.vars ?? [],
    notify: config.notify ?? [],
  };
}

const GENERATED_HEADER = "// Generated by `vera20k build` from vera.json; do not edit.";

const ascii = (name, what) => {
  if (typeof name !== "string" || !/^[\x21-\x7e]+$/.test(name) || name.length > 0xffff)
    fail(`${what} ${JSON.stringify(name)}: names are printable ASCII without spaces`);
  return name;
};

function uniqueFolded(names, what) {
  const seen = new Map();
  for (const name of names) {
    const folded = name.toLowerCase();
    if (seen.has(folded)) fail(`${what} ${JSON.stringify(name)} repeats ${JSON.stringify(seen.get(folded))} (names ignore case)`);
    seen.set(folded, name);
  }
}

// ------------------------------------------------------------ Generated

function identifier(name) {
  const id = name.replace(/[^A-Za-z0-9_$]/g, "_");
  return /^[0-9]/.test(id) ? `_${id}` : id;
}

/** `src/generated/vars.ts` (and `notify.ts`): one constant per declaration. */
function writeGenerated(dir, config) {
  const out = join(dir, dirname(config.entry), "generated");
  // A client module reads the simulation module's declarations by name; it
  // declares none itself, and must not import the simulation SDK.
  const ui = config.kind === "ui";
  const classes = ui
    ? { global: "ClientVar", house: "ClientVar", object: "ClientVar" }
    : { global: "GlobalVar", house: "HouseVar", object: "ObjectVar" };
  const sdk = ui ? "@vera20k/sdk/client" : "@vera20k/sdk";
  if (config.vars.length) {
    mkdirSync(out, { recursive: true });
    const used = [...new Set(config.vars.map((v) => classes[v.scope] ?? "ClientVar"))].sort();
    let text = GENERATED_HEADER + "\n\n" +
      `import { ${used.join(", ")} } from "${sdk}";\n\n`;
    for (const v of config.vars) text += `export const ${identifier(v.name)} = new ${classes[v.scope] ?? "ClientVar"}(${JSON.stringify(v.name)});\n`;
    updateGenerated(join(out, "vars.ts"), text);
  }
  if (!config.vars.length) updateGenerated(join(out, "vars.ts"));
  if (!config.notify.length) updateGenerated(join(out, "notify.ts"));
  if (config.notify.length) {
    mkdirSync(out, { recursive: true });
    const notify = ui ? "NotifyName" : "Notify";
    let text = GENERATED_HEADER + "\n\n" +
      `import { ${notify} } from "${sdk}";\n\n`;
    for (const name of config.notify) text += `export const ${identifier(name)} = new ${notify}(${JSON.stringify(name)});\n`;
    updateGenerated(join(out, "notify.ts"), text);
  }
}

function updateGenerated(path, text) {
  if (existsSync(path)) {
    const previous = readFileSync(path, "utf8");
    if (previous === text) return;
    if (!previous.startsWith(GENERATED_HEADER + "\n")) {
      if (text !== undefined) fail(`cannot generate ${path}: it contains hand-written source`);
      return;
    }
    if (text === undefined) rmSync(path);
  }
  if (text !== undefined) writeFileSync(path, text);
}

// ------------------------------------------------------- Custom sections

class Bytes {
  constructor() { this.parts = []; }
  u8(v) { this.parts.push(Buffer.from([v & 0xff])); return this; }
  u16(v) { const b = Buffer.alloc(2); b.writeUInt16LE(v); this.parts.push(b); return this; }
  u32(v) { const b = Buffer.alloc(4); b.writeUInt32LE(v >>> 0); this.parts.push(b); return this; }
  i32(v) { const b = Buffer.alloc(4); b.writeInt32LE(v | 0); this.parts.push(b); return this; }
  i64(v) { const b = Buffer.alloc(8); b.writeBigInt64LE(BigInt(v)); this.parts.push(b); return this; }
  name(s) { const b = Buffer.from(s, "ascii"); return this.u16(b.length).raw(b); }
  raw(b) { this.parts.push(b); return this; }
  done() { return Buffer.concat(this.parts); }
}

function leb(n) {
  const out = [];
  do {
    let byte = n & 0x7f;
    n >>>= 7;
    if (n) byte |= 0x80;
    out.push(byte);
  } while (n);
  return Buffer.from(out);
}

function customSection(name, payload) {
  const nameBytes = Buffer.from(name, "ascii");
  const body = Buffer.concat([leb(nameBytes.length), nameBytes, payload]);
  return Buffer.concat([Buffer.from([0]), leb(body.length), body]);
}

function sections(config, found, kind) {
  const out = [];
  out.push(customSection("vera.delivery", new Bytes().u8(1).u32(DELIVERY_OFFSET).u32(DELIVERY_BYTES).done()));
  if (found.actions.length) {
    const b = new Bytes().u8(1).u32(found.actions.length);
    for (const name of found.actions) b.name(name).i32(actionKey(name));
    out.push(customSection("vera.actions", b.done()));
  }
  if (kind === "rules" && config.vars.length) {
    const b = new Bytes().u8(1).u32(config.vars.length);
    for (const v of config.vars) {
      const scope = SCOPES[v.scope];
      const visibility = VISIBILITY[(v.visibility ?? "private").toLowerCase()];
      if (scope === undefined) fail(`vera.json: variable ${v.name}: scope must be global, house or object`);
      if (visibility === undefined) fail(`vera.json: variable ${v.name}: visibility must be private, allies, insight or public`);
      b.name(v.name).u8(scope).u8(visibility).i64(v.initial ?? v.default ?? 0);
    }
    out.push(customSection("vera.vars", b.done()));
  }
  if (kind === "rules" && config.notify.length) {
    const b = new Bytes().u8(1).u32(config.notify.length);
    for (const name of config.notify) b.name(name);
    out.push(customSection("vera.notify", b.done()));
  }
  return out;
}

// ----------------------------------------------------------------- Build

/** A `node_modules` holding only this SDK, so a project resolves `@vera20k/sdk` to the SDK of this command. */
let sdkModules;
function sdkPath() {
  if (sdkModules) return sdkModules;
  const root = mkdtempSync(join(tmpdir(), "vera20k-sdk-"));
  process.on("exit", () => rmSync(root, { recursive: true, force: true }));
  const link = join(root, "node_modules", "@vera20k", "sdk");
  mkdirSync(dirname(link), { recursive: true });
  symlinkSync(SDK, link, process.platform === "win32" ? "junction" : "dir");
  sdkModules = join(root, "node_modules");
  return sdkModules;
}

/** Validates `vera.json` and writes `src/generated/` (what `tsc` needs before a first build). */
export function generate(dir) {
  dir = resolve(dir);
  const config = readConfig(dir);
  for (const v of config.vars) {
    ascii(v.name, "variable");
    if (config.kind === "rules" && SCOPES[v.scope] === undefined)
      fail(`vera.json: variable ${v.name}: scope must be global, house or object`);
  }
  for (const name of config.notify) ascii(name, "notification");
  uniqueFolded(config.vars.map((v) => v.name), "variable");
  uniqueFolded(config.notify, "notification");
  writeGenerated(dir, config);
  return config;
}

export async function build(dir, options = {}) {
  dir = resolve(dir);
  const config = generate(dir);

  const world = WORLDS[config.kind];
  const out = resolve(dir, options.out ?? config.out);
  mkdirSync(dirname(out), { recursive: true });
  const found = { actions: [], uses: new Set() };
  const exportsFile = join(SDK, world.exports);
  // The transform finds the exports entry by its path as the compiler
  // normalizes it: relative to the working directory, `/`-separated.
  const exportsPath = relative(process.cwd(), exportsFile).split("\\").join("/");
  globalThis.__vera20kBuild = { found, exportsPath };

  const args = [
    join(dir, config.entry),
    exportsFile,
    "-o", out,
    "--path", sdkPath(),
    "--transform", join(SDK, "bin/transform.js"),
    "--runtime", "incremental",
    "--exportStart", world.start,
    "--use", `abort=~lib/@vera20k/sdk/assembly/abort/${world.abort}`,
    "--memoryBase", String(MEMORY_BASE),
    "--noAssert",
    ...(options.debug ? ["--debug", "-O1"] : ["-O3", "--shrinkLevel", "2", "--converge"]),
  ];
  let stderr = "";
  let wasm;
  const result = await asc.main(args, {
    writeFile: (file, bytes, baseDir) => {
      if (resolve(baseDir, file) === out) wasm = Buffer.from(bytes);
    },
    stdout: { write: (s) => process.stdout.write(s) },
    stderr: { write: (s) => { stderr += s; process.stderr.write(s); } },
  });
  if (found.error) fail(found.error);
  if (result.error) fail(`compile failed${stderr ? "" : `: ${result.error.message}`}`);

  uniqueFolded(found.actions, "named action");
  const keys = new Map();
  for (const name of found.actions) {
    const key = actionKey(name);
    if (keys.has(key)) fail(`named actions ${JSON.stringify(keys.get(key))} and ${JSON.stringify(name)} share dispatch key ${key}; rename one`);
    keys.set(key, name);
  }
  if (!wasm) fail("compiler did not produce the requested module");
  // The engine refuses a module importing the other world's functions
  // (RFC 3): say which call did it here, at build time.
  const world2 = config.kind === "ui" ? "vera:client@1.0" : "vera:sim@1.0";
  const foreign = WebAssembly.Module.imports(new WebAssembly.Module(wasm)).filter((i) => i.module !== world2);
  if (foreign.length) {
    fail(`a ${config.kind === "ui" ? "client" : "simulation"} module may import only ${world2}, but this one imports ` +
      foreign.map((i) => `${i.module}.${i.name}`).join(", ") +
      (config.kind === "ui" ? " (use Client.get and the other @vera20k/sdk/client calls, not the simulation SDK's)" : ""));
  }
  const complete = Buffer.concat([wasm, ...sections(config, found, config.kind)]);
  const staging = mkdtempSync(join(dirname(out), ".vera20k-build-"));
  try {
    const staged = join(staging, "module.wasm");
    writeFileSync(staged, complete);
    renameSync(staged, out);
  } finally {
    rmSync(staging, { recursive: true, force: true });
  }
  console.log(`${relative(process.cwd(), out) || out}: ${complete.length} bytes` +
    (found.actions.length ? `, actions ${found.actions.join(", ")}` : ""));
  return out;
}

// ----------------------------------------------------------------- Init

/** A new project in `dir` from the SDK's template; `ui` makes a client module. */
export function init(dir, ui) {
  dir = resolve(dir);
  if (existsSync(dir) && readdirSync(dir).length) fail(`${dir} is not empty`);
  cpSync(join(SDK, "template"), dir, { recursive: true });
  renameSync(join(dir, "gitignore"), join(dir, ".gitignore"));
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  pkg.name = dir.split(/[\\/]/).pop().toLowerCase().replace(/[^a-z0-9-]/g, "-");
  // An SDK run from a checkout rather than installed from a registry: depend
  // on that checkout.
  if (!SDK.split(/[\\/]/).includes("node_modules")) pkg.devDependencies["@vera20k/sdk"] = `file:${SDK}`;
  writeFileSync(join(dir, "package.json"), JSON.stringify(pkg, null, 2) + "\n");
  if (ui) {
    const config = JSON.parse(readFileSync(join(dir, "vera.json"), "utf8"));
    config.kind = "ui";
    delete config.vars;
    delete config.notify;
    writeFileSync(join(dir, "vera.json"), JSON.stringify(config, null, 2) + "\n");
    writeFileSync(join(dir, "src/index.ts"), 'import { Client, onStart } from "@vera20k/sdk/client";\n\n' +
      "// Runs once when the match interface is ready.\nonStart((): void => {\n  Client.log(\"Hello from my first client module!\");\n});\n");
  }
  console.log(`created ${dir}: npm install, then npm run build`);
}

// ------------------------------------------------------------------ CLI

async function main(argv) {
  const [command, ...rest] = argv;
  const options = {};
  let dir = ".";
  for (let i = 0; i < rest.length; i++) {
    if (rest[i] === "--out") options.out = rest[++i];
    else if (rest[i] === "--debug") options.debug = true;
    else dir = rest[i];
  }
  const run = async () => {
    try {
      await build(dir, options);
      return true;
    } catch (error) {
      if (!error.vera) throw error;
      console.error(`vera20k: ${error.message}`);
      return false;
    }
  };
  if (command === "init") {
    try {
      init(rest.find((a) => !a.startsWith("--")) ?? fail("usage: vera20k init <dir> [--ui]"), rest.includes("--ui"));
    } catch (error) {
      if (!error.vera) throw error;
      console.error(`vera20k: ${error.message}`);
      process.exitCode = 1;
    }
  } else if (command === "generate") {
    try {
      generate(dir);
    } catch (error) {
      if (!error.vera) throw error;
      console.error(`vera20k: ${error.message}`);
      process.exitCode = 1;
    }
  } else if (command === "build") {
    process.exitCode = (await run()) ? 0 : 1;
  } else if (command === "watch") {
    await run();
    const src = join(resolve(dir), dirname(readConfig(resolve(dir)).entry));
    let timer = null;
    console.log(`watching ${src}`);
    watch(src, { recursive: true }, (_event, file) => {
      if (file && file.startsWith("generated")) return;
      clearTimeout(timer);
      timer = setTimeout(run, 100);
    });
    watch(join(resolve(dir), "vera.json"), () => { clearTimeout(timer); timer = setTimeout(run, 100); });
  } else {
    console.log("usage: vera20k init <dir> [--ui]\n       vera20k build [dir] [--out file] [--debug]\n       vera20k watch [dir] [--out file] [--debug]\n       vera20k generate [dir]");
    process.exitCode = command ? 1 : 0;
  }
}

// Run as a command, also through npm's `node_modules/.bin` symlink.
if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) await main(process.argv.slice(2));
