//! Registered ordinary YR command metadata, in original 532150 registration order.
//! Source: tools/storage_oracle/keyboard_bindings.py executes original registration;
//! each CSF key is read from the registered object getter, not inferred from its name.

use super::HotkeyCommand;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct CommandMetadata {
    pub command: HotkeyCommand,
    pub ini_name: &'static str,
    pub name_key: &'static str,
    pub category_key: &'static str,
    pub description_key: &'static str,
    /// Original object +4 argument for the team/taunt localized printf format.
    pub parameter: Option<u8>,
}

macro_rules! command {
    ($command:expr, $ini:literal, $name:literal, $category:literal, $description:literal, $parameter:expr) => {
        CommandMetadata {
            command: $command,
            ini_name: $ini,
            name_key: $name,
            category_key: $category,
            description_key: $description,
            parameter: $parameter,
        }
    };
}

pub(crate) fn registered_commands() -> &'static [CommandMetadata] {
    #[cfg(any(feature = "verax", feature = "phobos"))]
    {
        use std::sync::OnceLock;
        static ALL: OnceLock<Vec<CommandMetadata>> = OnceLock::new();
        ALL.get_or_init(|| {
            let mut all = RETAIL_COMMANDS.to_vec();
            #[cfg(feature = "verax")]
            all.extend_from_slice(&VERA_COMMANDS);
            #[cfg(feature = "phobos")]
            all.extend_from_slice(&PHOBOS_COMMANDS);
            all
        })
    }
    #[cfg(not(any(feature = "verax", feature = "phobos")))]
    {
        retail_commands()
    }
}

/// Original gamemd registration only; the keyboard-page fixture compares it
/// row for row, so VeraX's own commands stay outside it.
pub(crate) fn retail_commands() -> &'static [CommandMetadata] {
    &RETAIL_COMMANDS
}

